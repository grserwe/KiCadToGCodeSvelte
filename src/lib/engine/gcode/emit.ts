/** Different-net copper keeps at least this gap even with a very fine tool. */
const MINIMUM_CLEARANCE_MM = 0.1;

export interface GenerateResult {
	files: GCodeFile[];
	warnings: EngineWarning[];
	/** The board as machined: thin tracks/pads widened (clearance-capped). */
	board: BoardModel;
}

/** Generate every output file for a board. */
export function generateGCode(
	designedBoard: BoardModel,
	boardName: string,
	settings: GCodeSettings,
	generatedAt: Date
): GenerateResult {
	const warnings: EngineWarning[] = [];
	const files: GCodeFile[] = [];
	const extension = settings.fileExtension || '.txt';

	// Widen thin copper toward the configured minimums first, capped so
	// different-net features keep an isolation channel between them.
	const widening = applyMinimumWidths(designedBoard, {
		minimumTrackWidthMm: settings.minimumTrackWidthMm,
		minimumPadDiameterMm: settings.minimumViaSizeMm,
		clearanceMm: Math.max(effectiveToolDiameterMm(settings), MINIMUM_CLEARANCE_MM)
	});
	const board = widening.board;
	warnings.push(...widening.warnings);

	for (const layer of ['top', 'bottom'] as const) {
		const { lines, warnings: layerWarnings } = isolationFile(
			board,
			boardName,
			settings,
			layer,
			generatedAt
		);
		warnings.push(...layerWarnings);
		files.push({
			fileName: `${boardName}-${layer}-isolation${extension}`,
			label: layer === 'top' ? 'Top isolation engraving' : 'Bottom isolation engraving (mirrored)',
			kind: layer === 'top' ? 'isolation-top' : 'isolation-bottom',
			machining: { facing: layer, sideMirror: layer === 'bottom' && settings.mirrorBottom },
			content: lines.join('\n') + '\n'
		});
	}

	if (settings.registrationHoles.enabled) {
		files.push(registrationFile(board, boardName, settings, generatedAt, extension));
	}

	for (const file of drillFiles(board, boardName, settings, generatedAt, extension)) {
		files.push(file);
	}

	if (settings.profile.enabled) {
		const profile = profileFile(board, boardName, settings, generatedAt, extension);
		warnings.push(...profile.warnings);
		if (profile.file) files.push(profile.file);
	}

	const silkscreen = generateSilkscreenFiles(board, boardName, settings);
	files.push(...silkscreen.files);
	warnings.push(...silkscreen.warnings);

	return { files, warnings, board };
}

function header(
	boardName: string,
	fileType: string,
	side: string,
	generatedAt: Date,
	extraLines: string[] = []
): string[] {
	return [
		`( ${boardName} ${fileType} GCode )`,
		`( Side: ${side} )`,
		...extraLines,
		`( Generated Timestamp: ${generatedAt.toISOString()} )`,
		'( Generated by KiCadToGCode )'
	];
}

function initialize(settings: GCodeSettings, safeZ: number, spindleRPM: number): string[] {
	return [
		g.useUnits(settings.outputUnits),
		g.absoluteCoordinates,
		g.xyPlane,
		g.rapidZ(safeZ),
		g.rapidXY(0, 0, settings.useMachineRapids ? undefined : settings.xyRapidSpeed),
		g.startSpindle(spindleRPM),
		g.pause
	];
}

function tearDown(settings: GCodeSettings, safeZ: number): string[] {
	return [
		g.rapidZ(safeZ),
		g.rapidXY(0, 0, settings.useMachineRapids ? undefined : settings.xyRapidSpeed),
		g.stopSpindle,
		g.endProgram
	];
}

/** A toolpath segment mapped into machine output coordinates. */
interface OutputSegment {
	start: Vec2;
	end: Vec2;
	arc: {
		center: Vec2;
		/** True when the machine sees this arc as clockwise start → end. */
		clockwise: boolean;
	} | null;
}

function toOutputSegments(segments: PathSegment[], transform: OutputTransform): OutputSegment[] {
	return segments.map((segment) => {
		if (segment.kind === 'line') {
			return {
				start: transform.point(segment.start),
				end: transform.point(segment.end),
				arc: null
			};
		}
		return {
			start: transform.point(arcPoint(segment, segment.startAngle)),
			end: transform.point(arcPoint(segment, segment.endAngle)),
			arc: {
				center: transform.point(segment.center),
				// Model arcs travel clockwise; each mirror flips the handedness.
				clockwise: !transform.mirrored
			}
		};
	});
}

function isolationFile(
	board: BoardModel,
	boardName: string,
	settings: GCodeSettings,
	layer: LayerId,
	generatedAt: Date
): { lines: string[]; warnings: EngineWarning[] } {
	const warnings: EngineWarning[] = [];
	const toolDiameter = effectiveToolDiameterMm(settings);
	const sideMirror = layer === 'bottom' && settings.mirrorBottom;
	const transform = createOutputTransform(settings, board.width, board.height, sideMirror);

	const sideNote =
		layer === 'bottom' && settings.mirrorBottom
			? ['( Mirrored for flip-over machining: flip the blank left-over-right )']
			: [];
	const lines = [
		...header(boardName, 'Isolation', layer === 'top' ? 'Top' : 'Bottom', generatedAt, [
			...sideNote,
			`( Tool: ${toolDiameter.toFixed(3)} mm effective diameter, ${settings.isolationPasses} pass${settings.isolationPasses === 1 ? '' : 'es'} )`
		]),
		...initialize(settings, settings.isolationSafeZ, settings.isolationSpindleRPM)
	];

	let position: Vec2 = { x: 0, y: 0 };
	let firstCut = true;

	for (let pass = 0; pass < Math.max(1, settings.isolationPasses); pass++) {
		const isolationOffset = toolDiameter / 2 + pass * settings.isolationStepover * toolDiameter;
		// Minimum widths were already applied (clearance-capped) to the board;
		// clamping again here could undo a cap and short the board.
		const toolpath = buildLayerToolpath(board, layer, {
			isolationOffset,
			minimumTrackWidth: 0,
			minimumPadDiameter: 0
		});
		if (pass === 0) {
			warnings.push(...toolpath.warnings);
		}
		if (settings.isolationPasses > 1) {
			lines.push(`( Pass ${pass + 1}: offset ${isolationOffset.toFixed(3)} mm )`);
		}
		position = walkSegments(
			toOutputSegments(toolpath.segments, transform),
			position,
			firstCut,
			settings,
			lines
		);
		firstCut = false;
	}

	lines.push(...tearDown(settings, settings.isolationSafeZ));
	return { lines, warnings };
}

/**
 * Greedy nearest-neighbour walk: repeatedly cut the unprocessed segment whose
 * nearest endpoint is closest to the tool, lifting to safe Z only between
 * discontinuous segments. Returns the final tool position.
 */
function walkSegments(
	segments: OutputSegment[],
	startPosition: Vec2,
	toolIsUp: boolean,
	settings: GCodeSettings,
	lines: string[]
): Vec2 {
	const remaining = [...segments];
	let position = startPosition;
	let needsPlunge = toolIsUp;

	while (remaining.length > 0) {
		let bestIndex = 0;
		let bestDistance = Infinity;
		let enterAtStart = true;
		for (let index = 0; index < remaining.length; index++) {
			const segment = remaining[index];
			const dStart = distance(position, segment.start);
			const dEnd = distance(position, segment.end);
			const nearest = Math.min(dStart, dEnd);
			if (nearest < bestDistance) {
				bestDistance = nearest;
				bestIndex = index;
				enterAtStart = dStart <= dEnd;
			}
		}

		const segment = remaining.splice(bestIndex, 1)[0];
		const entry = enterAtStart ? segment.start : segment.end;
		const exit = enterAtStart ? segment.end : segment.start;

		if (needsPlunge || distance(position, entry) > 0.0001) {
			lines.push(g.rapidZ(settings.isolationSafeZ));
			lines.push(
				g.rapidXY(entry.x, entry.y, settings.useMachineRapids ? undefined : settings.xyRapidSpeed)
			);
			lines.push(g.moveZ(-settings.isolationDepth, settings.isolationPlungeSpeed));
			needsPlunge = false;
		}

		if (segment.arc) {
			const clockwise = enterAtStart ? segment.arc.clockwise : !segment.arc.clockwise;
			lines.push(
				g.arcMove(
					clockwise,
					exit.x,
					exit.y,
					segment.arc.center.x - entry.x,
					segment.arc.center.y - entry.y
				)
			);
		} else {
			lines.push(g.moveXY(exit.x, exit.y, settings.isolationXYSpeed));
		}

		position = exit;
	}

	return position;
}

interface DrillTarget {
	position: Vec2;
	diameterMm: number;
}

function drillTargets(board: BoardModel): DrillTarget[] {
	return board.pads
		.filter((pad) => pad.drill && pad.drill.diameter > 0 && pad.layers === 'through')
		.map((pad) => ({ position: pad.position, diameterMm: pad.drill!.diameter }));
}

function drillFiles(
	board: BoardModel,
	boardName: string,
	settings: GCodeSettings,
	generatedAt: Date,
	extension: string
): GCodeFile[] {
	const targets = drillTargets(board);
	const diameters = [...new Set(targets.map((t) => t.diameterMm))].sort((a, b) => a - b);
	const sideMirror = settings.drillSide === 'bottom' && settings.mirrorBottom;
	const transform = createOutputTransform(settings, board.width, board.height, sideMirror);

	return diameters.map((diameter) => {
		const lines = [
			...header(
				boardName,
				'Drill',
				settings.drillSide === 'bottom' ? 'Bottom (board flipped)' : 'Top',
				generatedAt,
				[`( Drill Size: ${diameter} mm )`]
			),
			...initialize(settings, settings.drillingSafeZ, settings.drillingSpindleRPM)
		];

		const holes = targets
			.filter((target) => target.diameterMm === diameter)
			.map((target) => transform.point(target.position));
		emitDrillSequence(holes, settings, lines);

		lines.push(...tearDown(settings, settings.drillingSafeZ));

		return {
			fileName: `${boardName}-drill-${diameter}mm${extension}`,
			label: `Drill ${diameter} mm holes (${holes.length})`,
			kind: 'drill' as const,
			drillDiameterMm: diameter,
			machining: { facing: settings.drillSide, sideMirror },
			content: lines.join('\n') + '\n'
		};
	});
}

/** Drill each hole nearest-first from the current position. */
function emitDrillSequence(holes: Vec2[], settings: GCodeSettings, lines: string[]): void {
	const remaining = [...holes];
	let position: Vec2 = { x: 0, y: 0 };

	while (remaining.length > 0) {
		let bestIndex = 0;
		let bestDistance = Infinity;
		for (let index = 0; index < remaining.length; index++) {
			const d = distance(position, remaining[index]);
			if (d < bestDistance) {
				bestDistance = d;
				bestIndex = index;
			}
		}
		const hole = remaining.splice(bestIndex, 1)[0];

		lines.push(
			g.rapidXY(hole.x, hole.y, settings.useMachineRapids ? undefined : settings.xyRapidSpeed)
		);
		lines.push(g.moveZ(-settings.drillDepth, settings.drillingPlungeSpeed));
		lines.push(g.moveZ(settings.drillingSafeZ, settings.drillingRetractSpeed));

		position = hole;
	}
}

/** A stretch of a cutter path, flagged when it crosses a holding tab. */
export interface ProfilePiece {
	edge: OutlineEdge;
	inTab: boolean;
}

/**
 * Where along a loop (distance from its start, mm) the holding tabs sit:
 * `count` tabs of `width` spread evenly over the straight edges, kept clear
 * of the corner arcs where a tab would be awkward to snap off. A loop with
 * too little straight edge (a round board) spreads them over everything.
 */
export function tabCenters(edges: OutlineEdge[], count: number, width: number): number[] {
	if (count <= 0 || width <= 0) return [];
	const total = edges.reduce((sum, edge) => sum + edge.length, 0);
	const straight = edges
		.filter((edge) => edge.kind === 'line')
		.reduce((sum, edge) => sum + edge.length, 0);

	if (straight < 2 * width || straight < total * 0.25) {
		const tabs = Math.min(count, Math.floor(total / (2 * width)));
		return Array.from({ length: tabs }, (_, index) => (total / tabs) * (index + 0.5));
	}

	const tabs = Math.min(count, Math.max(1, Math.floor(straight / (2 * width))));
	const spacing = straight / tabs;
	const centers: number[] = [];
	let along = 0;
	let alongStraight = 0;
	let nextTab = 0;
	for (const edge of edges) {
		if (edge.kind === 'line') {
			while (nextTab < tabs) {
				const target = spacing * (nextTab + 0.5);
				if (target >= alongStraight + edge.length) break;
				nextTab++;
				if (edge.length < width) continue; // too short to carry a whole tab
				const local = Math.min(
					Math.max(target - alongStraight, width / 2),
					edge.length - width / 2
				);
				centers.push(along + local);
			}
			alongStraight += edge.length;
		}
		along += edge.length;
	}
	return centers;
}

/** Split a closed loop into pieces at the holding-tab boundaries. */
export function splitLoopAtTabs(
	edges: OutlineEdge[],
	count: number,
	width: number
): ProfilePiece[] {
	const intervals = tabCenters(edges, count, width).map((center) => ({
		from: center - width / 2,
		to: center + width / 2
	}));
	if (intervals.length === 0) return edges.map((edge) => ({ edge, inTab: false }));
	const inTab = (along: number) =>
		intervals.some((interval) => along >= interval.from && along <= interval.to);

	const pieces: ProfilePiece[] = [];
	let offset = 0;
	for (const edge of edges) {
		const end = offset + edge.length;
		const cuts = [0];
		for (const interval of intervals) {
			for (const boundary of [interval.from, interval.to]) {
				const local = boundary - offset;
				if (local > 1e-6 && local < edge.length - 1e-6) cuts.push(local);
			}
		}
		cuts.sort((a, b) => a - b);
		cuts.push(edge.length);
		for (let index = 0; index + 1 < cuts.length; index++) {
			const from = cuts[index];
			const to = cuts[index + 1];
			if (to - from <= 1e-6) continue;
			pieces.push({
				edge: edge.slice(from, to),
				inTab: inTab(offset + (from + to) / 2)
			});
		}
		offset = end;
	}
	return pieces;
}

/**
 * The board cutout: an end mill traces every outline loop in depth passes.
 * Holes inside the board are cut first; the outer boundary last, with tabs
 * left standing on the final passes so the board stays put until snapped
 * free. Run after everything else — it separates the board from the blank.
 */
function profileFile(
	board: BoardModel,
	boardName: string,
	settings: GCodeSettings,
	generatedAt: Date,
	extension: string
): { file: GCodeFile | null; warnings: EngineWarning[] } {
	const profile = settings.profile;
	const toolpath = buildProfileToolpath(board, profile.toolDiameterMm);
	if (toolpath.loops.length === 0) return { file: null, warnings: toolpath.warnings };

	const sideMirror = profile.side === 'bottom' && settings.mirrorBottom;
	const transform = createOutputTransform(settings, board.width, board.height, sideMirror);
	const units = settings.outputUnits;
	const rapidFeed = settings.useMachineRapids ? undefined : settings.xyRapidSpeed;

	const depth = Math.max(profile.depth, 0);
	const perPass = Math.max(profile.depthPerPass, 1e-4);
	const passCount = Math.max(1, Math.ceil(depth / perPass - 1e-9));
	const passDepths = Array.from({ length: passCount }, (_, index) =>
		Math.min(depth, perPass * (index + 1))
	);
	const tabHeight = convertLength(profile.tabHeightMm, 'mm', units);
	const tabTopZ = Math.min(0, -(depth - tabHeight));
	const tabCount = Math.max(0, Math.round(profile.tabCount));
	const unitLabel = units === 'inch' ? 'in' : 'mm';

	const lines = [
		...header(
			boardName,
			'Profile',
			profile.side === 'bottom' ? 'Bottom (board flipped)' : 'Top',
			generatedAt,
			[
				...(sideMirror
					? ['( Mirrored for flip-over machining: flip the blank left-over-right )']
					: []),
				`( Tool: ${profile.toolDiameterMm} mm end mill )`,
				`( Depth: ${depth} ${unitLabel} in ${passCount} pass${passCount === 1 ? '' : 'es'} of ${perPass} ${unitLabel} )`,
				tabCount > 0
					? `( Tabs: ${tabCount} x ${profile.tabWidthMm} mm wide, ${profile.tabHeightMm} mm tall, on the outer edge )`
					: '( Tabs: none — hold the board down )',
				'( Run this file last: it cuts the board free )'
			]
		),
		...initialize(settings, profile.safeZ, profile.spindleRPM)
	];

	for (const loop of toolpath.loops) {
		// Mirrored output reverses travel; flip the loop so the machine still climb mills.
		const oriented = transform.mirrored ? reverseProfileLoop(loop) : loop;
		const pieces = splitLoopAtTabs(
			oriented.edges,
			oriented.outer ? tabCount : 0,
			profile.tabWidthMm
		);
		const start = transform.point(pieces[0].edge.start);

		lines.push(oriented.outer ? '( Board outline )' : '( Cutout inside the board )');
		lines.push(g.rapidZ(profile.safeZ));
		lines.push(g.rapidXY(start.x, start.y, rapidFeed));

		let z = profile.safeZ;
		for (const passDepth of passDepths) {
			const passZ = -passDepth;
			const tabsActive = passZ < tabTopZ - 1e-9;
			for (const piece of pieces) {
				const targetZ = tabsActive && piece.inTab ? tabTopZ : passZ;
				if (Math.abs(z - targetZ) > 1e-9) {
					lines.push(g.moveZ(targetZ, profile.plungeSpeed));
					z = targetZ;
				}
				lines.push(profileMove(piece.edge, transform, profile.xySpeed));
			}
		}
		lines.push(g.rapidZ(profile.safeZ));
	}

	lines.push(...tearDown(settings, profile.safeZ));

	return {
		file: {
			fileName: `${boardName}-profile${extension}`,
			label: `Board cutout, ${profile.toolDiameterMm} mm end mill${sideMirror ? ' (mirrored)' : ''} — run last`,
			kind: 'profile',
			toolDiameterMm: profile.toolDiameterMm,
			machining: { facing: profile.side, sideMirror },
			content: lines.join('\n') + '\n'
		},
		warnings: toolpath.warnings
	};
}

/** The feed move along one edge, in machine coordinates. */
function profileMove(edge: OutlineEdge, transform: OutputTransform, feedRate: number): string {
	const end = transform.point(edge.end);
	if (edge.kind === 'line') return g.moveXY(end.x, end.y, feedRate);
	const start = transform.point(edge.start);
	const center = transform.point(edge.center);
	// A right-curving (clockwise) arc stays clockwise unless the output is mirrored.
	const clockwise = edge.sweep < 0 !== transform.mirrored;
	return g.arcMove(clockwise, end.x, end.y, center.x - start.x, center.y - start.y, feedRate);
}

/**
 * Registration holes for double-sided machining: two holes on the horizontal
 * centerline, symmetric about the mirror axis, outside the left/right board
 * edges — they land at the same machine positions from either side. Run this
 * file first, then pin the blank.
 */
function registrationFile(
	board: BoardModel,
	boardName: string,
	settings: GCodeSettings,
	generatedAt: Date,
	extension: string
): GCodeFile {
	const margin = settings.registrationHoles.marginMm;
	const holesModel: Vec2[] = [
		{ x: -margin, y: board.height / 2 },
		{ x: board.width + margin, y: board.height / 2 }
	];
	const transform = createOutputTransform(settings, board.width, board.height, false);
	const holes = holesModel.map((hole) => transform.point(hole));

	const lines = [
		...header(boardName, 'Registration Drill', 'Either (run first)', generatedAt, [
			`( Drill Size: ${settings.registrationHoles.diameterMm} mm )`,
			'( Pin these holes to realign the blank after flipping )'
		]),
		...initialize(settings, settings.drillingSafeZ, settings.drillingSpindleRPM)
	];
	emitDrillSequence(holes, settings, lines);
	lines.push(...tearDown(settings, settings.drillingSafeZ));

	return {
		fileName: `${boardName}-registration${extension}`,
		label: `Registration holes ${settings.registrationHoles.diameterMm} mm — run first`,
		kind: 'registration',
		drillDiameterMm: settings.registrationHoles.diameterMm,
		machining: { facing: 'top', sideMirror: false },
		content: lines.join('\n') + '\n'
	};
}
